create policy "lan_events_select_own" on public.lan_agent_events for select to authenticated using (exists (select 1 from public.lan_agents a where a.id = lan_agent_events.agent_id and a.user_id = auth.uid()));

create or replace function public.lan_create_pairing_key()
returns table(pairing_key text, expires_at timestamptz)
language plpgsql security definer set search_path = public, extensions as $$
declare v_user uuid := auth.uid(); v_code text; v_exp timestamptz := now() + interval '10 minutes';
begin
  if v_user is null then raise exception 'authentication required'; end if;
  delete from public.lan_pairing_requests where user_id = v_user and claimed_at is null and expires_at < now();
  v_code := upper(substr(encode(extensions.gen_random_bytes(8), 'hex'), 1, 12));
  insert into public.lan_pairing_requests(user_id, code_hash, expires_at)
  values (v_user, encode(extensions.digest(v_code, 'sha256'), 'hex'), v_exp);
  return query select v_code, v_exp;
end; $$;
revoke all on function public.lan_create_pairing_key() from public;
grant execute on function public.lan_create_pairing_key() to authenticated;

create or replace function public.lan_claim_pairing(p_pairing_key text,p_agent_name text,p_platform text,p_agent_version text,p_capabilities jsonb,p_token_hash text)
returns uuid language plpgsql security definer set search_path = public, extensions as $$
declare v_pair public.lan_pairing_requests%rowtype; v_agent_id uuid;
begin
  if char_length(coalesce(p_token_hash,'')) <> 64 then raise exception 'invalid token hash'; end if;
  select * into v_pair from public.lan_pairing_requests
  where code_hash = encode(extensions.digest(upper(trim(p_pairing_key)), 'sha256'), 'hex') and claimed_at is null and expires_at > now()
  order by created_at desc limit 1 for update;
  if v_pair.id is null then raise exception 'invalid or expired pairing key'; end if;
  insert into public.lan_agents(user_id,name,platform,agent_version,capabilities,status)
  values(v_pair.user_id,left(coalesce(nullif(trim(p_agent_name),''),'LAN Agent'),80),left(coalesce(p_platform,''),80),left(coalesce(p_agent_version,''),40),coalesce(p_capabilities,'{}'::jsonb),'offline')
  returning id into v_agent_id;
  insert into public.lan_agent_credentials(agent_id,token_hash) values(v_agent_id,lower(p_token_hash));
  update public.lan_pairing_requests set claimed_at=now(),agent_id=v_agent_id where id=v_pair.id;
  insert into public.lan_agent_events(agent_id,event_type,detail) values(v_agent_id,'paired',jsonb_build_object('platform',p_platform,'agent_version',p_agent_version));
  return v_agent_id;
end; $$;
revoke all on function public.lan_claim_pairing(text,text,text,text,jsonb,text) from public, anon, authenticated;
grant execute on function public.lan_claim_pairing(text,text,text,text,jsonb,text) to service_role;

