create extension if not exists pgcrypto with schema extensions;

create table if not exists public.lan_agents (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  status text not null default 'offline' check (status in ('online','offline')),
  lan_ip inet,
  public_ip inet,
  tailscale_ip inet,
  platform text,
  agent_version text,
  capabilities jsonb not null default '{}'::jsonb,
  last_latency_ms integer check (last_latency_ms is null or last_latency_ms >= 0),
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists lan_agents_user_id_idx on public.lan_agents(user_id);
create index if not exists lan_agents_last_seen_idx on public.lan_agents(last_seen_at desc);

create table if not exists public.lan_agent_credentials (
  agent_id uuid primary key references public.lan_agents(id) on delete cascade,
  token_hash text not null unique check (char_length(token_hash) = 64),
  created_at timestamptz not null default now(),
  last_rotated_at timestamptz not null default now()
);

create table if not exists public.lan_pairing_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  code_hash text not null unique check (char_length(code_hash) = 64),
  expires_at timestamptz not null,
  claimed_at timestamptz,
  agent_id uuid references public.lan_agents(id) on delete set null,
  created_at timestamptz not null default now(),
  check (expires_at > created_at)
);
create index if not exists lan_pairing_requests_user_id_idx on public.lan_pairing_requests(user_id, created_at desc);
create index if not exists lan_pairing_requests_expires_idx on public.lan_pairing_requests(expires_at);

create table if not exists public.lan_proxies (
  id uuid primary key default gen_random_uuid(),
  agent_id uuid not null references public.lan_agents(id) on delete cascade,
  host inet not null,
  port integer not null check (port between 1 and 65535),
  protocol text not null check (protocol in ('http','https','socks5')),
  enabled boolean not null default true,
  healthy boolean not null default false,
  latency_ms integer check (latency_ms is null or latency_ms >= 0),
  last_checked_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(agent_id, host, port, protocol)
);
create index if not exists lan_proxies_agent_id_idx on public.lan_proxies(agent_id);

create table if not exists public.lan_agent_commands (
  id uuid primary key default gen_random_uuid(),
  agent_id uuid not null references public.lan_agents(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  command_type text not null check (command_type in ('rescan','validate_proxy','set_proxy_enabled','rename_agent')),
  payload jsonb not null default '{}'::jsonb,
  status text not null default 'queued' check (status in ('queued','acknowledged','completed','failed')),
  created_at timestamptz not null default now(),
  acknowledged_at timestamptz,
  completed_at timestamptz,
  error_message text
);
create index if not exists lan_agent_commands_agent_queue_idx on public.lan_agent_commands(agent_id, status, created_at);

create table if not exists public.lan_agent_events (
  id bigint generated by default as identity primary key,
  agent_id uuid not null references public.lan_agents(id) on delete cascade,
  event_type text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

